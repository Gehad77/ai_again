import pg from 'pg';
import {readFileSync} from 'node:fs';
if(!process.env.DATABASE_URL)throw new Error('Set DATABASE_URL to a PostgreSQL connection URL. See README.md.');
// Monetary values retain NUMERIC precision in PostgreSQL; the demo API returns JSON numbers.
pg.types.setTypeParser(1700,Number);
export const pool=new pg.Pool({connectionString:process.env.DATABASE_URL,max:10,connectionTimeoutMillis:10000});
pool.on('error',()=>console.error('PostgreSQL connection error; check database availability.'));
export async function initialize(){
 const c=await pool.connect();
 try{await c.query('BEGIN');
 await c.query(`CREATE TABLE IF NOT EXISTS users(id INTEGER PRIMARY KEY CHECK(id=1),email TEXT NOT NULL,password_hash TEXT NOT NULL,salt TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY,expires_at TIMESTAMPTZ NOT NULL);
 CREATE SEQUENCE IF NOT EXISTS product_ids START 1000;
 CREATE SEQUENCE IF NOT EXISTS order_ids START 1000;`);
 await c.query(`CREATE TABLE IF NOT EXISTS conversations(id INTEGER PRIMARY KEY,name TEXT NOT NULL,initials TEXT NOT NULL,channel TEXT NOT NULL,product TEXT NOT NULL,status TEXT NOT NULL,intent TEXT NOT NULL,color TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS products(id INTEGER PRIMARY KEY,name TEXT NOT NULL,category TEXT NOT NULL,price NUMERIC(12,2) NOT NULL CHECK(price>=0),stock INTEGER NOT NULL CHECK(stock>=0),emoji TEXT NOT NULL,color TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS messages(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,conversation_id INTEGER NOT NULL REFERENCES conversations(id),role TEXT NOT NULL CHECK(role IN ('customer','assistant','agent')),body TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
 CREATE INDEX IF NOT EXISTS messages_conversation_idx ON messages(conversation_id,id);
 CREATE TABLE IF NOT EXISTS orders(id INTEGER PRIMARY KEY,product_id INTEGER NOT NULL REFERENCES products(id),quantity INTEGER NOT NULL CHECK(quantity>0),unit_price NUMERIC(12,2) NOT NULL CHECK(unit_price>=0),unit_cost NUMERIC(12,2) NOT NULL CHECK(unit_cost>=0),channel TEXT NOT NULL,status TEXT NOT NULL,date TIMESTAMPTZ NOT NULL);`);
 await c.query(`CREATE SEQUENCE IF NOT EXISTS conversation_ids START 1000;
 CREATE TABLE IF NOT EXISTS customers(id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,name TEXT NOT NULL,email TEXT UNIQUE NOT NULL,password_hash TEXT NOT NULL,salt TEXT NOT NULL,conversation_id INTEGER UNIQUE NOT NULL REFERENCES conversations(id));
 CREATE TABLE IF NOT EXISTS customer_sessions(token TEXT PRIMARY KEY,customer_id INTEGER NOT NULL REFERENCES customers(id),expires_at TIMESTAMPTZ NOT NULL);
 CREATE TABLE IF NOT EXISTS conversation_orders(order_id INTEGER PRIMARY KEY REFERENCES orders(id),conversation_id INTEGER NOT NULL REFERENCES conversations(id),request_key TEXT UNIQUE NOT NULL);`);
 await c.query(`
 CREATE TABLE IF NOT EXISTS used_owner_access_codes(digest BYTEA PRIMARY KEY);
 CREATE TABLE IF NOT EXISTS owner_recovery(
  owner_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  request_id TEXT NOT NULL, code_hash BYTEA NOT NULL, expires_at TIMESTAMPTZ NOT NULL,
  next_request TIMESTAMPTZ NOT NULL, attempts INTEGER NOT NULL DEFAULT 0
 );
 ALTER TABLE customers ADD COLUMN IF NOT EXISTS registered_at TIMESTAMPTZ;
 ALTER TABLE customers ALTER COLUMN registered_at SET DEFAULT CURRENT_TIMESTAMP;`);
 await c.query(`ALTER TABLE products ADD COLUMN IF NOT EXISTS unit_cost NUMERIC(12,2) CHECK(unit_cost>=0);
 ALTER TABLE orders ADD COLUMN IF NOT EXISTS paid_at TIMESTAMPTZ;
 CREATE TABLE IF NOT EXISTS stock_movements(
  id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  product_id INTEGER NOT NULL REFERENCES products(id), order_id INTEGER UNIQUE REFERENCES orders(id),
  delta INTEGER NOT NULL CHECK(delta<>0), stock_after INTEGER NOT NULL CHECK(stock_after>=0),
  kind TEXT NOT NULL CHECK(kind IN ('opening','sale','restock','correction','writeoff')),
  note TEXT NOT NULL DEFAULT '', unit_cost NUMERIC(12,2), date TIMESTAMPTZ NOT NULL DEFAULT NOW()
 );
 CREATE TABLE IF NOT EXISTS operating_expenses(
  id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  description TEXT NOT NULL, amount NUMERIC(12,2) NOT NULL CHECK(amount>0), date DATE NOT NULL
 );
 ALTER TABLE operating_expenses
  ADD COLUMN IF NOT EXISTS category TEXT NOT NULL DEFAULT 'Uncategorized',
  ADD COLUMN IF NOT EXISTS included_in_product_cost BOOLEAN NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS product_id INTEGER REFERENCES products(id);
 CREATE TABLE IF NOT EXISTS sales_targets(
  period TEXT PRIMARY KEY, amount NUMERIC(12,2) NOT NULL CHECK(amount>=0)
 );`);
 if(process.env.SEED_DEMO==='1'){
 const d=JSON.parse(readFileSync(new URL('./public/demo-data.json',import.meta.url),'utf8'));
 for(const x of d.overview.conversations)await c.query('INSERT INTO conversations VALUES($1,$2,$3,$4,$5,$6,$7,$8) ON CONFLICT DO NOTHING',[x.id,x.name,x.initials,x.channel,x.product,x.status,x.intent,x.color]);
 for(const x of d.overview.products)await c.query('INSERT INTO products VALUES($1,$2,$3,$4,$5,$6,$7) ON CONFLICT DO NOTHING',[x.id,x.name,x.category,x.price,x.stock,x.emoji,x.color]);
 for(const x of Object.values(d.messages).flat())await c.query('INSERT INTO messages(id,conversation_id,role,body,created_at) VALUES($1,$2,$3,$4,$5) ON CONFLICT DO NOTHING',[x.id,x.conversation_id,x.role,x.body,x.created_at+'Z']);
 for(const x of d.overview.orders)await c.query('INSERT INTO orders VALUES($1,$2,$3,$4,$5,$6,$7,$8) ON CONFLICT DO NOTHING',[x.id,x.product_id,x.quantity,x.unit_price,x.unit_cost,x.channel,x.status,x.date]);
 await c.query("SELECT setval(pg_get_serial_sequence('messages','id'),COALESCE((SELECT MAX(id) FROM messages),1),(SELECT COUNT(*)>0 FROM messages))");
 }
 await c.query('COMMIT');
 }catch(e){await c.query('ROLLBACK');throw e;}finally{c.release();}
}
