export function translate(text){
 if(language!=='ar')return text;
 const value=text.trim();
 const match=value.match(/^(.*) \(([A-Z]{3})\)$/);
 if(match&&translations.has(match[1]))return text.replace(value,translations.get(match[1])+' ('+match[2]+')');
 const dynamic=[
  [/^Based on paid sales, recorded expenses and inventory write-offs\. (.+) · (.+)\.$/,(_,code,zone)=>'الحساب بناءً على المبيعات المدفوعة والمصاريف وإهلاك المخزون. '+code+' · '+zone+'.'],
  [/^(\d+) paid units$/,(_,n)=>n+' قطعة مدفوعة'],
  [/^Recorded spending for (.+)\. Change the report period above to see another month, quarter, or year\.$/,(_,p)=>'المصروفات المسجّلة للفترة '+p+'. غيّري فترة التقرير لاختيار شهر أو ربع سنة أو سنة.'],
  [/^Margin after linked costs (.+)$/,( _,n)=>'هامش الربح بعد المصاريف المرتبطة '+n],
  [/^Gross margin (.+)$/,(_,n)=>'هامش الربح الإجمالي '+n],
  [/^Net margin (.+)$/,(_,n)=>'هامش الربح الصافي '+n],
  [/^(\d+) of (\d+) steps completed$/,(_,n,m)=>'تم '+n+' من '+m+' خطوات']
 ];
 const translated=translations.get(value);
 if(translated)return text.replace(value,translated);
 for(const [pattern,replace] of dynamic)if(pattern.test(value))return text.replace(value,value.replace(pattern,replace));
 return text;
}

export function localize(root){
 if(language!=='ar'||!root)return;
 if(root.nodeType===Node.TEXT_NODE){
  if(root.parentElement?.closest('[data-user-content],script,style'))return;
  const result=translate(root.data);
  if(result!==root.data){
   const parent=root.parentElement;
   if(parent?.tagName==='OPTION'&&!parent.hasAttribute('value'))parent.value=parent.value;
   root.data=result;
  }
  return;
 }
 if(root.nodeType!==Node.ELEMENT_NODE||root.closest('[data-user-content],script,style'))return;
 for(const attr of ['placeholder','aria-label','title']){
  const value=root.getAttribute(attr);
  if(value){const translated=translate(value);if(translated!==value)root.setAttribute(attr,translated);}
 }
 for(const child of root.childNodes)localize(child);
}
